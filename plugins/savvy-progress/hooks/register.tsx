// Opens the agents pane, or closes it when it is up. A close the person made
// is remembered, so the pane does not open by itself at the next start.
async function togglePane($: EngineInterface): Promise<{ isOpen: boolean; isPlaced: boolean }> {
  const isOpen = (await $.ui.panes()).some(p => p.id === PANE)
  if (isOpen) {
    await $.ui.close({ id: PANE })
    await $.store.set(HIDDEN_KEY, true)
    return { isOpen: false, isPlaced: false }
  }
  await $.store.set(HIDDEN_KEY, false)
  const at = await $.clock.now()
  await update($, now, () => at)
  void refresh($).catch(() => undefined)
  const opened = await $.ui.open({ id: PANE, title: tr().pane })
  return { isOpen: true, isPlaced: opened.isPlaced }
}

async function autoOpen($: EngineInterface, key: string): Promise<void> {
  const p = await read($, panel)
  if (p.autoOpenedFor === key) return
  await update($, panel, prev => ({ ...prev, autoOpenedFor: key }))
  void $.ui.open({ id: PANE, title: tr().pane })
}

