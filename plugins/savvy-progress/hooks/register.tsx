let stopTicker: (() => void) | undefined
let lastTouchAt = 0
let lastNowAt = 0
let refreshing: Promise<void> | undefined

const walk = async ($: EngineInterface, base: string): Promise<string[]> => {
  const found: string[] = []
  const queue: string[] = ['']
  while (queue.length > 0 && found.length < MAX_WALK) {
    const dir = queue.shift() as string
    const entries = await $.fs.list(dir ? `${base}/${dir}` : base).catch(() => [])
    for (const entry of entries) {
      const path = dir ? `${dir}/${entry.name}` : entry.name
      if (entry.kind === 'dir' && !SKIP_DIRS.has(entry.name)) queue.push(path)
      else if (entry.kind === 'file') found.push(path)
    }
  }
  return found
}

const doRefresh = async ($: EngineInterface): Promise<void> => {
  // Only what this chat can reach: the session's project root, never the
  // enclosing repository above it.
  const base = await $.session.root().catch(() => $.session.cwd())
  const prefix = await $.process.run(['git', 'rev-parse', '--show-prefix'], { cwd: base })
  let list: string[]
  let dirtyNow: string[] = []

  if (prefix.exitCode === 0) {
    const inside = prefix.stdout.trim()
    const ls = await $.process.run(['git', 'ls-files', '--cached', '--others', '--exclude-standard', '--', '.'], {
      cwd: base,
    })
    list = ls.stdout.split('\n').filter(Boolean)
    const st = await $.process.run(['git', 'status', '--porcelain', '-z', '--untracked-files=all', '--', '.'], {
      cwd: base,
    })
    // Porcelain paths are relative to the repository top: keep those under the root.
    dirtyNow = parsePorcelain(st.stdout)
      .filter(p => p.startsWith(inside))
      .map(p => p.slice(inside.length))
  } else {
    list = await walk($, base)
  }

  const before = new Set(await read($, dirty))
  const current = new Set(dirtyNow)
  const marks = await read($, touched)
  const left = [...before].filter(p => !current.has(p) && marks[p]?.kind === 'edit')

  // File dates for the tree's right column: one directory listing per folder
  // (names, sizes, times), never a file's contents.
  const times: Record<string, number> = {}
  const folders = [...new Set(list.map(p => (p.includes('/') ? p.slice(0, p.lastIndexOf('/')) : '')))].slice(0, MAX_FOLDERS)
  for (const dir of folders) {
    const entries = await $.fs.list(dir ? `${base}/${dir}` : base).catch(() => [])
    for (const entry of entries) if (entry.kind === 'file') times[dir ? `${dir}/${entry.name}` : entry.name] = entry.mtimeMs
  }

  await update($, root, () => base)
  await update($, files, () => list)
  await update($, mtimes, () => times)
  await update($, dirty, () => dirtyNow)
  if (left.length > 0) await update($, committed, c => [...new Set([...c, ...left])])
}

const refresh = ($: EngineInterface): Promise<void> => {
  refreshing ??= doRefresh($).finally(() => {
    refreshing = undefined
  })
  return refreshing
}

// The pane's one timer. Every redraw gives the pane's buttons new handles,
// and a click that lands on the drawing just replaced is dropped by the
// surface, so the pane redraws as rarely as it can: running agents' clocks
// move every AGENT_CLOCK_MS, and the tree redraws once when the last live
// row's linger ends (to fade it). Live rows are tinted, not pulsed.
const AGENT_CLOCK_MS = 5000
const startTicker = ($: EngineInterface) => {
  if (stopTicker) return
  let wereFilesLive = true
  const timer = $.clock.every(1000, async () => {
    const areFilesLive = (await read($, active)).length > 0 || Date.now() - lastTouchAt <= LINGER_MS
    const areAgentsLive = (await read($, agents)).some(a => a.status === 'running')
    if (wereFilesLive && !areFilesLive) await update($, frame, n => (n + 1) % 1000)
    wereFilesLive = areFilesLive
    if (areAgentsLive) {
      const at = await $.clock.now()
      if (at - lastNowAt >= AGENT_CLOCK_MS) {
        lastNowAt = at
        await update($, now, () => at)
      }
    }
    if (!areFilesLive && !areAgentsLive && stopTicker) {
      stopTicker()
      stopTicker = undefined
    }
  })
  stopTicker = () => timer.cancel()
}

const track = async ($: EngineInterface, path: string, kind: Touch['kind'], run: () => Promise<ToolCallResult>) => {
  const base = await read($, root)
  const rel = relative(base, path)
  if (!rel) return run()

  const entry = `${kind}:${rel}`
  await update($, active, a => [...a, entry])
  startTicker($)
  try {
    const ran = await run()
    if (ran.deny === undefined && ran.isError !== true) {
      await update($, touched, t => ({
        ...t,
        [rel]: { kind: t[rel]?.kind === 'edit' ? 'edit' : kind, at: Date.now() },
      }))
      if (kind === 'edit') {
        await update($, committed, c => c.filter(p => p !== rel))
        await update($, files, f => (f.includes(rel) ? f : [...f, rel]))
        await update($, dirty, d => (d.includes(rel) ? d : [...d, rel]))
      }
    }
    return ran
  } finally {
    lastTouchAt = Date.now()
    await update($, active, a => {
      const i = a.indexOf(entry)
      return i < 0 ? a : [...a.slice(0, i), ...a.slice(i + 1)]
    })
  }
}

// From the card to the tree: open the file's folders, mark its row, and
// scroll it to the middle of the pane. `collapse all` clears the mark.
const reveal = async ($: EngineInterface, path: string) => {
  await update($, expanded, x => {
    const next = { ...x }
    for (const dir of ancestors(path)) next[dir] = true
    return next
  })
  await update($, focused, () => path)
  await $.ui.scroll({ to: { key: `f:${path}` }, in: PANE, block: 'center' }).catch(() => undefined)
}

